import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const GUI_ROOT = path.resolve(SCRIPT_DIR, '..');
const REPO_ROOT = path.resolve(GUI_ROOT, '..', '..');

const SOURCE = path.resolve(REPO_ROOT, '.kiro/specs/audio-video-polish/linux-capability-matrix.md');
const TARGET = path.resolve(GUI_ROOT, 'src/features/voice/linux-capability-matrix.ts');
const CHECK_MODE = process.argv.includes('--check');

const HEADER = [
  'Desktop env',
  'Compositor',
  'Screen video (Video_Capture_Linux)',
  'System audio (Audio_Capture_Linux)',
  'Status',
  'User message',
  'Notes',
];

function parseMarkdownRow(line) {
  return line
    .trim()
    .replace(/^\|/, '')
    .replace(/\|$/, '')
    .split('|')
    .map((cell) => cell.trim());
}

function extractRuntimeRows(markdown) {
  const lines = markdown.split(/\r?\n/);
  const headerIndex = lines.findIndex((line) => {
    const cells = parseMarkdownRow(line);
    return cells.length === HEADER.length && cells.every((cell, index) => cell === HEADER[index]);
  });

  if (headerIndex === -1) {
    throw new Error(`could not find runtime matrix header in ${SOURCE}`);
  }

  const rows = [];
  for (let index = headerIndex + 2; index < lines.length; index += 1) {
    const line = lines[index];
    if (!line.trim().startsWith('|')) {
      break;
    }
    const cells = parseMarkdownRow(line);
    if (cells.length !== HEADER.length) {
      throw new Error(`unexpected runtime matrix row shape at line ${index + 1}`);
    }
    rows.push(cells);
  }

  return rows;
}

function parseCapability(cell, allowed) {
  const value = cell.split(/\s+/)[0]?.toLowerCase();
  if (!allowed.includes(value)) {
    throw new Error(`invalid capability "${cell}"`);
  }
  return value;
}

function normalizeRuntimeRow(cells) {
  const [
    desktopEnv,
    compositor,
    videoCaptureCell,
    audioCaptureCell,
    combinedStatusCell,
    userMessageCell,
  ] = cells;
  const compositorValue = compositor.toLowerCase();
  if (compositorValue !== 'wayland' && compositorValue !== 'x11') {
    throw new Error(`runtime compositor must be x11 or wayland, got "${compositor}"`);
  }

  return {
    desktopEnv: desktopEnv.toLowerCase(),
    compositor: compositorValue,
    videoCapture: parseCapability(videoCaptureCell, ['supported', 'unsupported']),
    audioCapture: parseCapability(audioCaptureCell, ['supported', 'degraded', 'unsupported']),
    combinedStatus: parseCapability(combinedStatusCell, ['supported', 'degraded', 'unsupported']),
    userMessage: userMessageCell.length > 0 ? userMessageCell : null,
  };
}

function renderRows(rows) {
  return rows
    .map((row) => {
      const userMessage = row.userMessage === null ? 'null' : JSON.stringify(row.userMessage);
      return `  {\n    desktopEnv: ${JSON.stringify(row.desktopEnv)},\n    compositor: ${JSON.stringify(row.compositor)},\n    videoCapture: ${JSON.stringify(row.videoCapture)},\n    audioCapture: ${JSON.stringify(row.audioCapture)},\n    combinedStatus: ${JSON.stringify(row.combinedStatus)},\n    userMessage: ${userMessage},\n  },`;
    })
    .join('\n');
}

function renderFile(rows) {
  return `// Generated by scripts/gen-linux-matrix.mjs from .kiro/specs/audio-video-polish/linux-capability-matrix.md
// Do not edit by hand.

export type LinuxCapabilityStatus = 'supported' | 'degraded' | 'unsupported';

export interface LinuxCapabilityRow {
  desktopEnv: string;
  compositor: 'wayland' | 'x11';
  videoCapture: 'supported' | 'unsupported';
  audioCapture: 'supported' | 'degraded' | 'unsupported';
  combinedStatus: LinuxCapabilityStatus;
  userMessage: string | null;
}

export const rows: LinuxCapabilityRow[] = [
${renderRows(rows)}
];

const UNKNOWN_COMBINATION_MESSAGE =
  'Linux native share on this desktop is not in the checked-in Wavis capability matrix yet; share will proceed with degraded expectations.';

export function lookupLinuxCapability(
  desktopEnv: string,
  compositor: 'wayland' | 'x11',
): LinuxCapabilityRow {
  const normalizedDesktopEnv = desktopEnv.trim().toLowerCase();
  return (
    rows.find((row) => row.desktopEnv === normalizedDesktopEnv && row.compositor === compositor) ?? {
      desktopEnv: normalizedDesktopEnv || 'unknown',
      compositor,
      videoCapture: 'unsupported',
      audioCapture: 'unsupported',
      combinedStatus: 'degraded',
      userMessage: UNKNOWN_COMBINATION_MESSAGE,
    }
  );
}
`;
}

const source = fs.readFileSync(SOURCE, 'utf8');
const rows = extractRuntimeRows(source).map(normalizeRuntimeRow);
const nextOutput = renderFile(rows);

if (CHECK_MODE) {
  const existingOutput = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (existingOutput !== nextOutput) {
    console.error('[linux-matrix] generated file is out of date. Run `npm run gen:linux-matrix`.');
    process.exit(1);
  }
  console.log('[linux-matrix] OK');
  process.exit(0);
}

fs.writeFileSync(TARGET, nextOutput, 'utf8');
console.log(`[linux-matrix] wrote ${path.relative(process.cwd(), TARGET)}`);
